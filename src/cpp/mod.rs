//! Layer 3 - the C++ code generator.
//!
//! Consumes the IR and produces a `.h` / `.cpp` pair. The generator is split
//! in components:
//!
//! * [`types`]  - Rust type -> C++ type mapping
//! * [`pat`]    - patterns -> conditions + bindings
//! * [`expr`]   - statements and expressions
//! * [`fmt`]    - `format!` strings -> `std::format` strings
//! * [`sym`]    - symbol table (enums, structs, traits) built before generation
//! * this file  - items: functions, structs, enums, traits, impls, modules

mod expr;
mod fmt;
mod pat;
mod sym;
mod types;

use crate::ir::*;
use expr::{LoopCtx, Target};
use std::collections::{HashMap, HashSet};
use sym::{Symbols, type_name};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CppStd {
    Cpp20,
    Cpp23,
}

impl CppStd {
    pub fn number(self) -> u32 {
        match self {
            CppStd::Cpp20 => 20,
            CppStd::Cpp23 => 23,
        }
    }
}

/// Resolves module references to header files (implemented by the file
/// system walker).
pub trait Resolver {
    /// Header to include for `mod name;`.
    fn mod_include(&self, name: &str) -> String {
        format!("{name}.h")
    }
    /// Header defining the module a `use crate::a::b::X` refers to.
    fn use_include(&self, _path: &[String]) -> Option<String> {
        None
    }
}

pub struct NoResolver;
impl Resolver for NoResolver {}

pub struct Options {
    pub std: CppStd,
    /// Include path of `rust_runtime.hpp` as seen from the generated header.
    pub runtime_include: String,
    /// C++ namespace the whole file lives in (derived from the module path).
    pub namespace: Vec<String>,
    pub resolver: Box<dyn Resolver>,
}

impl Default for Options {
    fn default() -> Self {
        Options {
            std: CppStd::Cpp20,
            runtime_include: "rust_runtime.hpp".into(),
            namespace: vec![],
            resolver: Box::new(NoResolver),
        }
    }
}

#[derive(Debug, Clone)]
pub struct Output {
    pub header: String,
    pub source: String,
}

const KEYWORDS: &[&str] = &[
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "case", "catch", "class", "compl",
    "concept", "const_cast", "consteval", "constexpr", "constinit", "co_await", "co_return", "co_yield", "decltype",
    "default", "delete", "double", "dynamic_cast", "explicit", "export", "extern", "float", "friend", "goto", "inline",
    "int", "long", "namespace", "new", "noexcept", "not", "not_eq", "nullptr", "operator", "or", "or_eq", "private",
    "protected", "public", "register", "reinterpret_cast", "requires", "short", "signed", "sizeof", "static_assert",
    "static_cast", "switch", "template", "this", "thread_local", "throw", "try", "typedef", "typeid", "typename",
    "union", "unsigned", "using", "virtual", "void", "volatile", "wchar_t", "xor", "xor_eq", "NULL", "errno",
    "assert", "main_",
];

/// Maps a Rust identifier to a valid C++ identifier.
pub fn id(s: &str) -> String {
    let s = s.strip_prefix("r#").unwrap_or(s);
    if KEYWORDS.contains(&s) { format!("{s}_") } else { s.to_string() }
}

/// Entry point of the generator.
pub fn generate(file: &File, stem: &str, opts: &Options) -> Output {
    let mut e = Emitter::new(opts, Symbols::collect(&file.items));
    let (mut h, mut s) = (String::new(), String::new());
    e.items(&file.items, &mut h, &mut s);

    let mut header = String::new();
    header.push_str(&format!(
        "// Generated by rust-to-cpp from `{stem}.rs` (C++{}). Do not edit.\n#pragma once\n\n",
        opts.std.number()
    ));
    header.push_str(&format!("#include \"{}\"\n", opts.runtime_include));
    for inc in &e.includes {
        header.push_str(&format!("#include \"{inc}\"\n"));
    }
    header.push_str(&format!(
        "\nstatic_assert(__cplusplus >= {}L, \"this file requires C++{}\");\n\n",
        if opts.std == CppStd::Cpp23 { "202100" } else { "202002" },
        opts.std.number()
    ));
    let ns = opts.namespace.join("::");
    if !ns.is_empty() {
        header.push_str(&format!("namespace {ns} {{\n\n"));
    }
    header.push_str(&h);
    if !ns.is_empty() {
        header.push_str(&format!("}}  // namespace {ns}\n"));
    }
    for t in &e.trailer {
        header.push('\n');
        header.push_str(t);
    }

    let mut source = format!("// Generated by rust-to-cpp from `{stem}.rs`. Do not edit.\n#include \"{stem}.h\"\n");
    if !s.trim().is_empty() {
        source.push('\n');
        if !ns.is_empty() {
            source.push_str(&format!("namespace {ns} {{\n\n"));
        }
        source.push_str(&s);
        if !ns.is_empty() {
            source.push_str(&format!("}}  // namespace {ns}\n"));
        }
    }
    Output { header, source }
}

pub struct Emitter<'a> {
    pub opts: &'a Options,
    pub sym: Symbols,
    pub lines: Vec<String>,
    pub pre: Vec<String>,
    pub ind: usize,
    pub tmp: usize,
    pub loops: Vec<LoopCtx>,
    pub used_labels: HashSet<String>,
    pub box_vars: HashSet<String>,
    pub self_name: Option<String>,
    pub self_free: bool,
    pub in_method: bool,
    pub is_main: bool,
    pub includes: Vec<String>,
    pub trailer: Vec<String>,
    ns: Vec<String>,
}

struct Saved {
    lines: Vec<String>,
    pre: Vec<String>,
    ind: usize,
    tmp: usize,
    loops: Vec<LoopCtx>,
    used_labels: HashSet<String>,
    box_vars: HashSet<String>,
    self_name: Option<String>,
    self_free: bool,
    in_method: bool,
    is_main: bool,
}

/// The pieces of a function signature.
struct Sig {
    templates: Vec<String>,
    attrs: String,
    ret: String,
    name: String,
    params: String,
    pat_params: Vec<(String, Pat)>,
    is_template: bool,
}

fn type_mentions(t: &Type, name: &str) -> bool {
    match t {
        Type::Path(segs) => segs.iter().any(|s| s.name == name || s.args.iter().any(|a| type_mentions(a, name))),
        Type::Ref { inner, .. } | Type::Ptr { inner, .. } | Type::Slice(inner) | Type::Array(inner, _) => type_mentions(inner, name),
        Type::Tuple(ts) => ts.iter().any(|t| type_mentions(t, name)),
        Type::Fn(a, r) => a.iter().any(|t| type_mentions(t, name)) || r.as_ref().is_some_and(|t| type_mentions(t, name)),
        _ => false,
    }
}

fn fields_types(f: &Fields) -> Vec<&Type> {
    match f {
        Fields::Named(n) => n.iter().map(|(_, t)| t).collect(),
        Fields::Tuple(t) => t.iter().collect(),
        Fields::Unit => vec![],
    }
}

fn indent_text(s: &str, n: usize) -> String {
    let pad = "    ".repeat(n);
    s.lines()
        .map(|l| if l.is_empty() { String::new() } else { format!("{pad}{l}") })
        .collect::<Vec<_>>()
        .join("\n")
}

fn operator_name(trait_: &str, f: &str) -> Option<&'static str> {
    Some(match (trait_, f) {
        ("Add", "add") => "operator+",
        ("Sub", "sub") => "operator-",
        ("Mul", "mul") => "operator*",
        ("Div", "div") => "operator/",
        ("Rem", "rem") => "operator%",
        ("Neg", "neg") => "operator-",
        ("Not", "not") => "operator!",
        ("BitAnd", "bitand") => "operator&",
        ("BitOr", "bitor") => "operator|",
        ("BitXor", "bitxor") => "operator^",
        ("Shl", "shl") => "operator<<",
        ("Shr", "shr") => "operator>>",
        ("AddAssign", "add_assign") => "operator+=",
        ("SubAssign", "sub_assign") => "operator-=",
        ("MulAssign", "mul_assign") => "operator*=",
        ("DivAssign", "div_assign") => "operator/=",
        ("PartialEq", "eq") => "operator==",
        ("Index", "index") => "operator[]",
        _ => return None,
    })
}

impl<'a> Emitter<'a> {
    fn new(opts: &'a Options, sym: Symbols) -> Self {
        Emitter {
            opts,
            sym,
            lines: vec![],
            pre: vec![],
            ind: 0,
            tmp: 0,
            loops: vec![],
            used_labels: HashSet::new(),
            box_vars: HashSet::new(),
            self_name: None,
            self_free: false,
            in_method: false,
            is_main: false,
            includes: vec![],
            trailer: vec![],
            ns: opts.namespace.clone(),
        }
    }

    fn save(&mut self) -> Saved {
        Saved {
            lines: std::mem::take(&mut self.lines),
            pre: std::mem::take(&mut self.pre),
            ind: self.ind,
            tmp: self.tmp,
            loops: std::mem::take(&mut self.loops),
            used_labels: std::mem::take(&mut self.used_labels),
            box_vars: std::mem::take(&mut self.box_vars),
            self_name: self.self_name.take(),
            self_free: self.self_free,
            in_method: self.in_method,
            is_main: self.is_main,
        }
    }

    fn restore(&mut self, s: Saved) {
        self.lines = s.lines;
        self.pre = s.pre;
        self.ind = s.ind;
        self.tmp = s.tmp;
        self.loops = s.loops;
        self.used_labels = s.used_labels;
        self.box_vars = s.box_vars;
        self.self_name = s.self_name;
        self.self_free = s.self_free;
        self.in_method = s.in_method;
        self.is_main = s.is_main;
    }

    /// Generates a declaration for an item nested in a function body.
    pub fn local_decl(&mut self, it: &Item) -> String {
        let saved = self.save();
        let (mut h, mut s) = (String::new(), String::new());
        self.items(std::slice::from_ref(it), &mut h, &mut s);
        self.restore(saved);
        format!("{}{}", h.trim_end(), if s.trim().is_empty() { String::new() } else { format!("\n{}", s.trim_end()) })
    }

    // ------------------------------------------------------------------
    // items
    // ------------------------------------------------------------------
    fn items(&mut self, items: &[Item], h: &mut String, s: &mut String) {
        // forward declarations
        let mut fwd = String::new();
        for it in items {
            match it {
                Item::Struct(st) => fwd.push_str(&format!("{}struct {};\n", self.template_line(&st.generics, ""), id(&st.name))),
                Item::Enum(e) if self.sym.enums.get(&e.name).is_some_and(|i| i.data) => {
                    fwd.push_str(&format!("{}struct {};\n", self.template_line(&e.generics, ""), id(&e.name)))
                }
                Item::Trait(t) => fwd.push_str(&format!("{}struct {};\n", self.template_line(&t.generics, ""), id(&t.name))),
                _ => {}
            }
        }
        if !fwd.is_empty() {
            h.push_str(&fwd);
            h.push('\n');
        }

        // impls that are attached to a type of this scope become members
        let local_types: HashSet<String> = items
            .iter()
            .filter_map(|i| match i {
                Item::Struct(s) => Some(s.name.clone()),
                Item::Enum(e) => Some(e.name.clone()),
                _ => None,
            })
            .collect();
        let mut attached: HashMap<String, Vec<&ImplDef>> = HashMap::new();
        for it in items {
            if let Item::Impl(i) = it {
                if let Some(n) = type_name(&i.self_ty) {
                    if local_types.contains(&n) {
                        attached.entry(n).or_default().push(i);
                    }
                }
            }
        }

        for it in items {
            match it {
                Item::Use(u) => self.emit_use(u, h),
                Item::ExternMod(m) => {
                    let inc = self.opts.resolver.mod_include(m);
                    if !self.includes.contains(&inc) {
                        self.includes.push(inc);
                    }
                }
                Item::Fn(f) => self.free_fn(f, h, s),
                Item::Struct(st) => {
                    let impls = attached.get(&st.name).cloned().unwrap_or_default();
                    self.emit_struct(st, &impls, h, s);
                }
                Item::Enum(e) => {
                    let impls = attached.get(&e.name).cloned().unwrap_or_default();
                    self.emit_enum(e, &impls, h, s);
                }
                Item::Impl(i) => {
                    let attached_here = type_name(&i.self_ty).is_some_and(|n| local_types.contains(&n));
                    if !attached_here {
                        self.emit_free_impl(i, h);
                    }
                }
                Item::Trait(t) => self.emit_trait(t, h),
                Item::Mod(m) => {
                    let (mut mh, mut ms) = (String::new(), String::new());
                    self.ns.push(m.name.clone());
                    self.items(&m.items, &mut mh, &mut ms);
                    self.ns.pop();
                    h.push_str(&format!("namespace {} {{\n\n{}}}  // namespace {}\n\n", id(&m.name), mh, id(&m.name)));
                    if !ms.trim().is_empty() {
                        s.push_str(&format!("namespace {} {{\n\n{}}}  // namespace {}\n\n", id(&m.name), ms, id(&m.name)));
                    }
                }
                Item::Const(c) => self.emit_const(c, h),
                Item::TypeAlias { name, generics, ty } => {
                    h.push_str(&format!("{}using {} = {};\n\n", self.template_line(generics, ""), id(name), self.ty(ty)));
                }
                Item::Unsupported(what) => h.push_str(&format!("// unsupported item: {what}\n\n")),
            }
        }
    }

    fn emit_use(&mut self, u: &UseDecl, h: &mut String) {
        let full = u.path.join("::");
        let first = u.path.first().map(String::as_str).unwrap_or("");
        let glob = if u.glob { "::*" } else { "" };
        match first {
            "std" | "core" | "alloc" => h.push_str(&format!("// use {full}{glob};\n")),
            "crate" | "self" | "super" => {
                if let Some(inc) = self.opts.resolver.use_include(&u.path) {
                    if !self.includes.contains(&inc) {
                        self.includes.push(inc);
                    }
                }
                let mut path: &[String] = &u.path;
                let mut abs = "";
                while !path.is_empty() && matches!(path[0].as_str(), "crate" | "self" | "super") {
                    if path[0] == "crate" {
                        abs = "::";
                    }
                    path = &path[1..];
                }
                if path.is_empty() {
                    h.push_str(&format!("// use {full}{glob};\n"));
                    return;
                }
                let joined = path.iter().map(|p| id(p)).collect::<Vec<_>>().join("::");
                let enum_name = if u.glob { path.last() } else { path.get(path.len().wrapping_sub(2)) };
                if let Some(info) = enum_name.and_then(|n| self.sym.enums.get(n)) {
                    if !info.data {
                        if u.glob {
                            h.push_str(&format!("using enum {abs}{joined};\n"));
                        } else {
                            h.push_str(&format!("using {abs}{joined};\n"));
                        }
                    } else {
                        h.push_str(&format!("// use {full}{glob}; (enum variants are named Enum_Variant)\n"));
                    }
                } else if u.glob {
                    h.push_str(&format!("using namespace {abs}{joined};\n"));
                } else if let Some(a) = &u.alias {
                    h.push_str(&format!("using {} = {abs}{joined};\n", id(a)));
                } else if path.len() == 1 {
                    h.push_str(&format!("// use {full}; (module)\n"));
                } else {
                    h.push_str(&format!("using {abs}{joined};\n"));
                }
            }
            _ => h.push_str(&format!("// use {full}{glob}; (external dependency)\n")),
        }
    }

    fn qualified(&self, name: &str) -> String {
        let mut p = self.ns.iter().map(|n| id(n)).collect::<Vec<_>>();
        p.push(id(name));
        format!("::{}", p.join("::"))
    }

    // ------------------------------------------------------------------
    // generics
    // ------------------------------------------------------------------
    fn template_params(&self, g: &Generics) -> Vec<String> {
        g.params
            .iter()
            .map(|p| match p {
                GenericParam::Type(n) => format!("typename {}", id(n)),
                GenericParam::Const(n, t) => format!("{} {}", self.ty(t), id(n)),
            })
            .collect()
    }

    fn requires_clause(&self, g: &Generics) -> Option<String> {
        let mut parts = Vec::new();
        for (ty, bounds) in &g.bounds {
            let t = self.ty(ty);
            for b in bounds {
                if let Some((args, _)) = &b.fn_sig {
                    let mut a = vec![t.clone()];
                    a.extend(args.iter().map(|x| self.ty(x)));
                    parts.push(format!("std::invocable<{}>", a.join(", ")));
                } else if self.sym.traits.get(&b.name) == Some(&false) {
                    parts.push(format!("Is{}<{t}>", id(&b.name)));
                }
            }
        }
        if parts.is_empty() { None } else { Some(parts.join(" && ")) }
    }

    /// `template <...>\n` (or empty) for a set of generics.
    fn template_line(&self, g: &Generics, _pad: &str) -> String {
        let p = self.template_params(g);
        if p.is_empty() { String::new() } else { format!("template <{}>\n", p.join(", ")) }
    }

    // ------------------------------------------------------------------
    // functions
    // ------------------------------------------------------------------
    fn sig(&mut self, f: &Function, name: &str) -> Sig {
        let mut params = Vec::new();
        let mut pat_params = Vec::new();
        let mut has_auto = false;
        if self.self_free {
            if let Some(r) = f.receiver {
                let st = self.self_name.clone().unwrap_or_default();
                params.push(match r {
                    Receiver::Ref => format!("const {st}& self"),
                    Receiver::RefMut => format!("{st}& self"),
                    Receiver::Value => format!("{st} self"),
                });
            }
        }
        for (i, p) in f.params.iter().enumerate() {
            let t = self.ty(&p.ty);
            has_auto |= t.contains("auto");
            match &p.pat {
                Pat::Ident { name, sub: None, .. } => params.push(format!("{t} {}", id(name))),
                Pat::Wild => params.push(format!("{t} _{i}")),
                other => {
                    let arg = format!("_arg{i}");
                    params.push(format!("{t} {arg}"));
                    pat_params.push((arg, other.clone()));
                }
            }
        }
        let mut attrs = String::new();
        if matches!(f.ret, Some(Type::Never)) {
            attrs.push_str("[[noreturn]] ");
        }
        let ret = if f.name == "main" && self.self_name.is_none() && !self.self_free { "int".to_string() } else { self.ret_ty(f.ret.as_ref()) };
        let tp = self.template_params(&f.generics);
        let mut templates = Vec::new();
        if !tp.is_empty() {
            templates.push(format!("template <{}>", tp.join(", ")));
        }
        if let Some(r) = self.requires_clause(&f.generics) {
            templates.push(format!("requires {r}"));
        }
        Sig {
            is_template: !tp.is_empty() || has_auto,
            templates,
            attrs,
            ret,
            name: name.to_string(),
            params: params.join(", "),
            pat_params,
        }
    }

    fn body_lines(&mut self, f: &Function, sig: &Sig, base: usize) -> Vec<String> {
        let Some(body) = &f.body else { return vec![] };
        self.lines.clear();
        self.pre.clear();
        self.loops.clear();
        self.used_labels.clear();
        self.box_vars.clear();
        self.tmp = 0;
        self.ind = base + 1;
        self.is_main = f.name == "main" && self.self_name.is_none() && !self.self_free;
        for p in &f.params {
            self.register_param(p);
        }
        let target = if self.is_main || matches!(f.ret, None | Some(Type::Unit) | Some(Type::Never)) {
            Target::Discard
        } else {
            Target::Return
        };
        let pat_params = sig.pat_params.clone();
        let lines = self.capture(|s| {
            for (arg, pat) in &pat_params {
                let (_, binds) = s.pat_cond(pat, arg);
                s.emit_binds(&binds);
            }
            s.block_into(body, &target);
        });
        self.is_main = false;
        lines
    }

    fn render(&self, sig: &Sig, prefix: &str, qualifier: &str, suffix: &str, body: Option<&[String]>) -> String {
        let mut out = String::new();
        for t in &sig.templates {
            out.push_str(t);
            out.push('\n');
        }
        let head = if sig.ret.is_empty() {
            format!("{}{}{}({}){}", sig.attrs, prefix, sig.name, sig.params, suffix)
        } else {
            format!("{}{}{} {}{}({}){}", sig.attrs, prefix, sig.ret, qualifier, sig.name, sig.params, suffix)
        };
        out.push_str(&head);
        match body {
            None => out.push_str(";\n"),
            Some(lines) => {
                out.push_str(" {\n");
                for l in lines {
                    out.push_str(l);
                    out.push('\n');
                }
                out.push_str("}\n");
            }
        }
        out
    }

    fn free_fn(&mut self, f: &Function, h: &mut String, s: &mut String) {
        let sig = self.sig(f, &id(&f.name));
        let is_main = f.name == "main";
        if is_main {
            let body = self.body_lines(f, &sig, 0);
            s.push_str(&self.render(&sig, "", "", "", Some(&body)));
            s.push('\n');
            return;
        }
        let header_only = sig.is_template || f.is_const;
        if header_only {
            let body = self.body_lines(f, &sig, 0);
            let prefix = if f.is_const { "constexpr " } else if sig.templates.is_empty() { "inline " } else { "" };
            h.push_str(&self.render(&sig, prefix, "", "", Some(&body)));
            h.push('\n');
        } else {
            h.push_str(&self.render(&sig, "", "", "", None));
            let body = self.body_lines(f, &sig, 0);
            s.push_str(&self.render(&sig, "", "", "", Some(&body)));
            s.push('\n');
        }
    }

    // ------------------------------------------------------------------
    // structs and enums
    // ------------------------------------------------------------------
    fn field_decls(&self, f: &Fields, pad: &str) -> String {
        let mut out = String::new();
        match f {
            Fields::Named(n) => {
                for (name, t) in n {
                    out.push_str(&format!("{pad}{} {};\n", self.ty(t), id(name)));
                }
            }
            Fields::Tuple(ts) => {
                for (i, t) in ts.iter().enumerate() {
                    out.push_str(&format!("{pad}{} _{i};\n", self.ty(t)));
                }
            }
            Fields::Unit => {}
        }
        out
    }

    fn bases(&self, impls: &[&ImplDef]) -> Vec<String> {
        let mut out: Vec<String> = Vec::new();
        for i in impls {
            if let Some(t) = &i.trait_ {
                if self.sym.local_trait(&t.name) {
                    let args = if t.args.is_empty() { String::new() } else { format!("<{}>", self.tys(&t.args)) };
                    let b = format!("public {}{}", id(&t.name), args);
                    if !out.contains(&b) {
                        out.push(b);
                    }
                }
            }
        }
        out
    }

    fn emit_struct(&mut self, st: &StructDef, impls: &[&ImplDef], h: &mut String, s: &mut String) {
        let name = id(&st.name);
        let saved_name = self.self_name.replace(name.clone());
        let bases = self.bases(impls);
        let mut body = String::new();
        body.push_str(&self.field_decls(&st.fields, "    "));
        let field_list: Vec<(String, String)> = match &st.fields {
            Fields::Named(n) => n.iter().map(|(f, t)| (id(f), self.ty(t))).collect(),
            Fields::Tuple(ts) => ts.iter().enumerate().map(|(i, t)| (format!("_{i}"), self.ty(t))).collect(),
            Fields::Unit => vec![],
        };
        if !bases.is_empty() && !field_list.is_empty() {
            let params = field_list.iter().map(|(n, t)| format!("{t} {n}")).collect::<Vec<_>>().join(", ");
            let inits = field_list.iter().map(|(n, _)| format!("{n}(std::move({n}))")).collect::<Vec<_>>().join(", ");
            body.push_str(&format!("\n    {name}() = default;\n    {name}({params}) : {inits} {{}}\n"));
        }
        body.push_str(&self.derive_ops(&st.derives, &name, !bases.is_empty()));
        let generic = !st.generics.params.is_empty();
        let extra = self.member_items(&name, generic, impls, &mut body, s);
        let base_str = if bases.is_empty() { String::new() } else { format!(" : {}", bases.join(", ")) };
        h.push_str(&format!("{}struct {name}{base_str} {{\n{body}}};\n\n", self.template_line(&st.generics, "")));
        h.push_str(&extra);
        self.self_name = saved_name;
    }

    fn derive_ops(&self, derives: &[String], name: &str, has_bases: bool) -> String {
        let mut out = String::new();
        if has_bases {
            return out;
        }
        let has = |d: &str| derives.iter().any(|x| x == d);
        if has("PartialOrd") || has("Ord") {
            out.push_str(&format!("\n    auto operator<=>(const {name}&) const = default;\n"));
            out.push_str(&format!("    bool operator==(const {name}&) const = default;\n"));
        } else if has("PartialEq") || has("Eq") {
            out.push_str(&format!("\n    bool operator==(const {name}&) const = default;\n"));
        }
        out
    }

    /// Emits the members coming from `impl` blocks: declarations into `body`,
    /// out-of-class definitions into `s`. Returns text that has to follow the
    /// class definition in the header.
    fn member_items(&mut self, class: &str, class_generic: bool, impls: &[&ImplDef], body: &mut String, s: &mut String) -> String {
        let mut after = String::new();
        let mut first = true;
        for imp in impls {
            let is_local_trait = imp.trait_.as_ref().is_some_and(|t| self.sym.local_trait(&t.name));
            let trait_name = imp.trait_.as_ref().map(|t| t.name.clone());
            let impl_generic = !imp.generics.params.is_empty();
            for c in &imp.consts {
                let prim = matches!(&c.ty, Type::Path(p) if p.len() == 1 && types::is_primitive(&p[0].name));
                let v = c.value.as_ref().map(|v| {
                    let sv = self.save();
                    self.self_name = Some(class.to_string());
                    let t = self.expr(v);
                    self.restore(sv);
                    t
                });
                let ty = self.ty(&c.ty);
                if prim {
                    body.push_str(&format!("    static constexpr {ty} {} = {};\n", id(&c.name), v.unwrap_or_default()));
                } else {
                    body.push_str(&format!("    static const {ty} {};\n", id(&c.name)));
                    if !class_generic {
                        after.push_str(&format!("inline const {ty} {class}::{} = {};\n\n", id(&c.name), v.unwrap_or_default()));
                    }
                }
            }
            for f in &imp.fns {
                if !first || !body.is_empty() {
                    if !body.ends_with("\n\n") {
                        body.push('\n');
                    }
                }
                first = false;
                if trait_name.as_deref() == Some("Drop") && f.name == "drop" {
                    let lines = self.method_body(f, class, 1, &Sig { templates: vec![], attrs: String::new(), ret: String::new(), name: String::new(), params: String::new(), pat_params: vec![], is_template: false });
                    body.push_str(&format!("    ~{class}() {{\n{}\n    }}\n", lines.join("\n")));
                    continue;
                }
                let op = trait_name.as_deref().and_then(|t| operator_name(t, &f.name));
                if trait_name.as_deref() == Some("Display") && !class_generic && !impl_generic {
                    let q = self.qualified(class);
                    self.trailer.push(format!(
                        "template <>\nstruct std::formatter<{q}> : std::formatter<std::string> {{\n    auto format(const {q}& v, auto& ctx) const {{\n        std::ostringstream os;\n        v.fmt(os);\n        return std::formatter<std::string>::format(os.str(), ctx);\n    }}\n}};\n"
                    ));
                }
                let saved = self.self_name.replace(class.to_string());
                let name = match op {
                    Some(o) => o.to_string(),
                    None => id(&f.name),
                };
                let mut sig = self.sig(f, &name);
                let is_static = f.receiver.is_none();
                let konst = matches!(f.receiver, Some(Receiver::Ref)) || (op.is_some() && f.receiver == Some(Receiver::Value));
                let suffix = if konst { " const" } else { "" };
                let inline = class_generic || impl_generic || sig.is_template || f.is_const || f.body.is_none();
                let virt_override = if is_local_trait && !is_static { " override" } else { "" };
                let prefix = if is_static { "static " } else { "" };
                // templates inside the class are plain member templates
                let tmpl = std::mem::take(&mut sig.templates);
                let sig_in = Sig { templates: tmpl.clone(), ..sig_clone(&sig) };
                if inline {
                    let lines = self.method_body(f, class, 2, &sig);
                    let text = self.render(&sig_in, &format!("{prefix}{}", if f.is_const { "constexpr " } else { "" }), "", &format!("{suffix}{virt_override}"), Some(&lines));
                    body.push_str(&indent_text(&text, 1));
                    body.push('\n');
                } else {
                    let text = self.render(&sig_in, prefix, "", &format!("{suffix}{virt_override}"), None);
                    body.push_str(&indent_text(&text, 1));
                    body.push('\n');
                    let lines = self.method_body(f, class, 1, &sig);
                    let def = self.render(&sig, "", &format!("{class}::"), suffix, Some(&lines));
                    s.push_str(&def);
                    s.push('\n');
                }
                self.self_name = saved;
            }
        }
        while body.ends_with("\n\n") {
            body.pop();
        }
        after
    }

    fn method_body(&mut self, f: &Function, class: &str, base: usize, sig: &Sig) -> Vec<String> {
        let saved_name = self.self_name.replace(class.to_string());
        let saved_method = std::mem::replace(&mut self.in_method, f.receiver.is_some());
        let lines = self.body_lines(f, sig, base - 1);
        self.in_method = saved_method;
        self.self_name = saved_name;
        lines
    }

    fn emit_free_impl(&mut self, imp: &ImplDef, h: &mut String) {
        let tname = type_name(&imp.self_ty).unwrap_or_else(|| "T".into());
        let self_ty = self.ty(&imp.self_ty);
        let prefix = match &imp.trait_ {
            Some(t) => format!("{}_{}", tname, t.name),
            None => tname,
        };
        let saved_name = self.self_name.replace(self_ty);
        let saved_free = std::mem::replace(&mut self.self_free, true);
        h.push_str(&format!("// impl for a type that is not a local struct/enum: emitted as free functions `{prefix}_<method>`\n"));
        for f in &imp.fns {
            let mut f2 = f.clone();
            f2.generics.params.extend(imp.generics.params.clone());
            let sig = self.sig(&f2, &format!("{prefix}_{}", id(&f.name)));
            let body = self.body_lines(f, &sig, 0);
            let pfx = if sig.templates.is_empty() { "inline " } else { "" };
            h.push_str(&self.render(&sig, pfx, "", "", Some(&body)));
            h.push('\n');
        }
        self.self_free = saved_free;
        self.self_name = saved_name;
    }

    fn emit_enum(&mut self, e: &EnumDef, impls: &[&ImplDef], h: &mut String, s: &mut String) {
        let name = id(&e.name);
        let info = self.sym.enums.get(&e.name).cloned();
        let data = info.as_ref().is_some_and(|i| i.data);
        if !data {
            let vs = e
                .variants
                .iter()
                .map(|v| match &v.discriminant {
                    Some(d) => format!("    {} = {}", id(&v.name), self.expr_const(d)),
                    None => format!("    {}", id(&v.name)),
                })
                .collect::<Vec<_>>()
                .join(",\n");
            h.push_str(&format!("enum class {name} {{\n{vs}\n}};\n\n"));
            return;
        }
        let saved_name = self.self_name.replace(name.clone());
        let eq = e.derives.iter().any(|d| d == "PartialEq" || d == "Eq");
        let mut alts = Vec::new();
        for v in &e.variants {
            let vname = format!("{name}_{}", id(&v.name));
            let used: Vec<&GenericParam> = e
                .generics
                .params
                .iter()
                .filter(|p| match p {
                    GenericParam::Type(n) => fields_types(&v.fields).iter().any(|t| type_mentions(t, n)),
                    GenericParam::Const(..) => false,
                })
                .collect();
            let g = Generics { params: used.iter().map(|p| (*p).clone()).collect(), bounds: vec![] };
            let args = if used.is_empty() {
                String::new()
            } else {
                format!(
                    "<{}>",
                    used.iter()
                        .map(|p| match p {
                            GenericParam::Type(n) | GenericParam::Const(n, _) => id(n),
                        })
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            };
            let eqop = if eq { format!("    bool operator==(const {vname}&) const = default;\n") } else { String::new() };
            h.push_str(&format!(
                "{}struct {vname} {{\n{}{eqop}}};\n\n",
                self.template_line(&g, ""),
                self.field_decls(&v.fields, "    ")
            ));
            alts.push(format!("{vname}{args}"));
        }
        let bases = self.bases(impls);
        let variant = format!("std::variant<{}>", alts.join(", "));
        let mut base_list = vec![format!("public {variant}")];
        base_list.extend(bases);
        let mut body = format!("    using {variant}::variant;\n");
        let generic = !e.generics.params.is_empty();
        let extra = self.member_items(&name, generic, impls, &mut body, s);
        h.push_str(&format!("{}struct {name} : {} {{\n{body}}};\n\n", self.template_line(&e.generics, ""), base_list.join(", ")));
        h.push_str(&extra);
        self.self_name = saved_name;
    }

    fn expr_const(&mut self, e: &Expr) -> String {
        let sv = self.save();
        let t = self.expr(e);
        self.restore(sv);
        t
    }

    // ------------------------------------------------------------------
    // traits and constants
    // ------------------------------------------------------------------
    fn emit_trait(&mut self, t: &TraitDef, h: &mut String) {
        let name = id(&t.name);
        let saved_name = self.self_name.replace(name.clone());
        let supers: Vec<String> = t
            .supertraits
            .iter()
            .filter(|b| self.sym.local_trait(&b.name))
            .map(|b| format!("public {}", id(&b.name)))
            .collect();
        let base = if supers.is_empty() { String::new() } else { format!(" : {}", supers.join(", ")) };
        let mut body = format!("    virtual ~{name}() = default;\n");
        for f in &t.fns {
            if f.receiver.is_none() || !f.generics.params.is_empty() {
                continue;
            }
            let sig = self.sig(f, &id(&f.name));
            let konst = if f.receiver == Some(Receiver::Ref) { " const" } else { "" };
            match &f.body {
                None => body.push_str(&format!("    virtual {} {}({}){konst} = 0;\n", sig.ret, sig.name, sig.params)),
                Some(_) => {
                    let lines = self.method_body(f, &name, 2, &sig);
                    body.push_str(&format!("    virtual {} {}({}){konst} {{\n{}\n    }}\n", sig.ret, sig.name, sig.params, lines.join("\n")));
                }
            }
        }
        h.push_str(&format!("{}struct {name}{base} {{\n{body}}};\n\n", self.template_line(&t.generics, "")));
        // C++20 concept used for generic bounds (`T: Trait`).
        if t.generics.params.is_empty() {
            self.self_name = Some("T".into());
            let mut reqs = Vec::new();
            for f in t.fns.iter().filter(|f| f.body.is_none() && f.generics.params.is_empty()) {
                let args = f.params.iter().map(|p| format!("std::declval<{}>()", self.ty(&p.ty))).collect::<Vec<_>>().join(", ");
                let call = if f.receiver.is_some() { format!("t.{}({args})", id(&f.name)) } else { format!("T::{}({args})", id(&f.name)) };
                reqs.push(format!("{call};"));
            }
            let reqs = if reqs.is_empty() { "t;".to_string() } else { reqs.join(" ") };
            h.push_str(&format!("template <typename T>\nconcept Is{name} = requires(T& t) {{ {reqs} }};\n\n"));
        }
        self.self_name = saved_name;
    }

    fn emit_const(&mut self, c: &ConstDef, h: &mut String) {
        let v = c.value.as_ref().map(|v| self.expr_const(v)).unwrap_or_default();
        let prim = matches!(&c.ty, Type::Path(p) if p.len() == 1 && types::is_primitive(&p[0].name))
            || matches!(&c.ty, Type::Ref { inner, .. } if matches!(&**inner, Type::Path(p) if p.len() == 1 && p[0].name == "str"));
        let kw = if c.mutable {
            "inline"
        } else if prim {
            "inline constexpr"
        } else {
            "inline const"
        };
        h.push_str(&format!("{kw} {} {} = {v};\n\n", self.ty(&c.ty), id(&c.name)));
    }
}

fn sig_clone(s: &Sig) -> Sig {
    Sig {
        templates: s.templates.clone(),
        attrs: s.attrs.clone(),
        ret: s.ret.clone(),
        name: s.name.clone(),
        params: s.params.clone(),
        pat_params: s.pat_params.clone(),
        is_template: s.is_template,
    }
}
